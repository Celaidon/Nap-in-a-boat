"""
Style judge evaluator calling Serverless Inference (OpenAI compatible) with local cache.
Evaluates writing quality on fluency, creativity, prompt following, structure, and overall score.
"""

import hashlib
import json
import os
import pathlib
import re

from openai import OpenAI


# Helper to load .env file manually if os.environ doesn't contain the key
def _load_env_file():
    env_path = pathlib.Path(".env")
    if env_path.exists():
        for line in env_path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                key, val = line.split("=", 1)
                os.environ.setdefault(key.strip(), val.strip())


_load_env_file()

CACHE_PATH = pathlib.Path("results/judge_cache.jsonl")


def _get_cache() -> dict[str, dict]:
    cache = {}
    if CACHE_PATH.exists():
        with CACHE_PATH.open("r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    try:
                        data = json.loads(line)
                        if "key" in data and "score" in data:
                            cache[data["key"]] = data["score"]
                    except (json.JSONDecodeError, KeyError):
                        continue
    return cache


def _write_cache(key: str, score: dict):
    CACHE_PATH.parent.mkdir(parents=True, exist_ok=True)
    with CACHE_PATH.open("a", encoding="utf-8") as f:
        f.write(json.dumps({"key": key, "score": score}) + "\n")


def _heuristic_fallback_judge(prompt: str, answer: str) -> dict:
    """Deterministic fallback judge when API key is missing or endpoint is unavailable."""
    if not answer or not answer.strip():
        return {"fluency": 1.0, "creativity": 1.0, "follows_prompt": 1.0, "structure": 1.0, "overall": 1.0}

    words = answer.strip().split()
    word_count = len(words)

    # Basic word count & length heuristic
    fluency = min(10.0, max(2.0, word_count / 15.0))
    creativity = min(10.0, max(2.0, len(set(words)) / max(1, word_count) * 10.0))
    follows_prompt = 7.0 if len(answer) > 20 else 3.0
    structure = 8.0 if "\n" in answer else 5.0

    overall = round((fluency + creativity + follows_prompt + structure) / 4.0, 1)

    return {
        "fluency": round(fluency, 1),
        "creativity": round(creativity, 1),
        "follows_prompt": round(follows_prompt, 1),
        "structure": round(structure, 1),
        "overall": overall,
    }


def judge_style(prompt: str, answer: str) -> dict:
    """Judge writing quality using JUDGE_MODEL API or cached/heuristic evaluation.

    Args:
        prompt: The evaluation prompt string.
        answer: The text generated by the candidate model.

    Returns:
        dict: {"fluency": float, "creativity": float, "follows_prompt": float, "structure": float, "overall": float}
    """
    api_key = os.environ.get("DO_MODEL_ACCESS_KEY", "").strip()
    judge_model = os.environ.get("JUDGE_MODEL", "meta-llama/Meta-Llama-3.1-70B-Instruct").strip()

    cache_key = hashlib.sha256(f"{judge_model}:{prompt}:{answer}".encode()).hexdigest()

    # 1. Check cache first
    cache = _get_cache()
    if cache_key in cache:
        return cache[cache_key]

    # 2. If API key missing, use fallback
    if not api_key:
        score = _heuristic_fallback_judge(prompt, answer)
        _write_cache(cache_key, score)
        return score

    # 3. Call OpenAI-compatible Serverless Inference API
    client = OpenAI(
        base_url="https://inference.do-ai.run/v1",
        api_key=api_key,
    )

    system_message = (
        "You are an expert writing judge. Evaluate the quality of the candidate's answer for the user prompt.\n"
        "Score each category from 1 to 10:\n"
        "- fluency: Grammatical quality, readability, and text flow\n"
        "- creativity: Originality, depth, and expressive quality\n"
        "- follows_prompt: Accuracy in fulfilling all prompt requirements\n"
        "- structure: Logical organization, line breaks, formatting\n"
        "- overall: General score reflecting overall response quality\n\n"
        "Output ONLY a valid JSON object matching this exact schema:\n"
        '{"fluency": 8, "creativity": 7, "follows_prompt": 9, "structure": 8, "overall": 8.0}'
    )

    user_message = f"Prompt: {prompt}\n\nCandidate Answer:\n{answer}"

    for attempt in range(2):
        try:
            resp = client.chat.completions.create(
                model=judge_model,
                messages=[
                    {"role": "system", "content": system_message},
                    {"role": "user", "content": user_message},
                ],
                temperature=0.0,
                max_tokens=256,
            )
            content = resp.choices[0].message.content or ""
            # Strip code fences if present
            cleaned = re.sub(r"```(?:json)?\s*|\s*```", "", content).strip()
            parsed = json.loads(cleaned)

            required_keys = {"fluency", "creativity", "follows_prompt", "structure", "overall"}
            if required_keys.issubset(set(parsed.keys())):
                score = {k: float(parsed[k]) for k in required_keys}
                _write_cache(cache_key, score)
                return score
        except Exception:  # noqa: BLE001, S110
            pass

    # Fallback if API or JSON parsing fails after 2 attempts
    score = _heuristic_fallback_judge(prompt, answer)
    _write_cache(cache_key, score)
    return score
