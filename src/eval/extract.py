"""
Extractor module to parse clean executable Python code out of model text answers.
Handles markdown fenced code blocks, explanations, and unfenced code blocks.
"""

import re


def extract_code(answer: str, entry_point: str) -> str:
    """Extract Python code block or snippet targeting entry_point from raw model answer.

    Args:
        answer: Raw output text generated by the model.
        entry_point: Expected function name (e.g. "remove_occ").

    Returns:
        Extracted Python code string.
    """
    if not answer or not answer.strip():
        return ""

    text = answer.strip()

    # Find all fenced code blocks ```python ... ``` or ``` ... ```
    fence_pattern = r"```(?:python)?\s*\n?(.*?)\n?\s*```"
    blocks = re.findall(fence_pattern, text, re.DOTALL | re.IGNORECASE)

    if blocks:
        # Prefer the block that contains "def <entry_point>"
        target_pattern = rf"\bdef\s+{re.escape(entry_point)}\b"
        for block in blocks:
            if re.search(target_pattern, block):
                return block.strip()
        # Fallback to the first fenced block
        return blocks[0].strip()

    # If no markdown fences are found, search for "def <entry_point>"
    def_pattern = rf"(\bdef\s+{re.escape(entry_point)}\b.*)"
    match = re.search(def_pattern, text, re.DOTALL)
    if match:
        return match.group(1).strip()

    # If nothing is found, return the whole answer
    return text
